/* =========================================================
   Into the Woods — Korean translation (KR)

   HOW IT WORKS
   - LANG is "en" or "ko". It's saved in localStorage. A ?lang=ko in
     the address (from a shared link) wins and gets saved too.
   - The EN / KR buttons on the start page save the choice and
     reload the page from the start.
   - KO.html swaps the text that's written in index.html /
     personalities.html (runs right away, before lace.js draws).
   - applyKoreanData() (called from script.js) swaps the story,
     results and friends/foes text that lives in script.js.
   - t(key, english) is used in script.js for the little lines
     that are built on the fly. Values can be text or functions.

   TONE: casual 반말, like a friend telling you the story.
   Keep it playful. Don't make it sound like a textbook.
   (The ranger is a stranger, so they talk in polite 해요체.)
   ========================================================= */

const LANG = (() => {
  const fromUrl = new URLSearchParams(window.location.search).get("lang");
  try {
    if (fromUrl === "ko" || fromUrl === "en") localStorage.setItem("lang", fromUrl);
    return localStorage.getItem("lang") === "ko" ? "ko" : "en";
  } catch {
    return fromUrl === "ko" ? "ko" : "en"; // localStorage blocked (private mode)
  }
})();

document.documentElement.lang = LANG;

// Korean name + the right "hey you" ending: 지민 -> 지민아, 수지 -> 수지야.
// Non-Korean names are left as they are.
function koVocative(name) {
  const code = name.charCodeAt(name.length - 1);
  if (code < 0xac00 || code > 0xd7a3) return name;
  return name + ((code - 0xac00) % 28 ? "아" : "야");
}

// Added to links we hand out (share links, the personalities page),
// so they open in Korean even if localStorage is blocked.
function langParam() {
  return LANG === "ko" ? "&lang=ko" : "";
}

// Look up a Korean line; fall back to the English one.
function t(key, en, ...args) {
  const pick = LANG === "ko" && KO.text[key] !== undefined ? KO.text[key] : en;
  return typeof pick === "function" ? pick(...args) : pick;
}

