// ---------------------------------------------------------
// Swap the story / result text that lives in script.js.
// script.js calls this once, after all its data is defined.
// ---------------------------------------------------------
function applyKoreanData() {
  if (LANG !== "ko") return;
  Object.assign(TYPES, KO.types);
  for (const key in KO.answers) ANSWERS[key].outcome = KO.answers[key];
  for (const type in KO.results) {
    const { alt, ...text } = KO.results[type];
    Object.assign(RESULTS[type], text);
    RESULTS[type].image.alt = alt;
  }
  Object.assign(POSTER, KO.poster);
  for (const type in KO.relations) {
    ["friends", "foes"].forEach((group) => {
      RELATIONS[type][group].forEach((pair, i) => {
        pair[1] = KO.relations[type][group][i];
      });
    });
  }
}

// ---------------------------------------------------------
// EN / KR buttons on the start page: save, then start over
// ---------------------------------------------------------
document.querySelectorAll("[data-lang]").forEach((button) => {
  const active = button.dataset.lang === LANG;
  button.classList.toggle("is-active", active);
  button.setAttribute("aria-pressed", active ? "true" : "false");
  button.addEventListener("click", () => {
    if (button.dataset.lang === LANG) return;
    try {
      localStorage.setItem("lang", button.dataset.lang);
    } catch {
      /* private mode: the ?lang= below still does the job for this visit */
    }
    window.location.href = `${window.location.pathname}?lang=${button.dataset.lang}`;
  });
});
